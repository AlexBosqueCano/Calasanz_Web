---------------------------------------------------------------------------------------------------------
-- Estructura de base de datos del CD. CALASANZ (M1 + M2 — Según API_CONTRATO.md §6)
---------------------------------------------------------------------------------------------------------

DROP TRIGGER IF EXISTS trg_check_goles_recibidos ON estadisticas_partido;
DROP FUNCTION IF EXISTS verificar_goles_portero();

DROP TABLE IF EXISTS solicitud_acceso CASCADE;
DROP TABLE IF EXISTS apunte_entrenador CASCADE;
DROP TABLE IF EXISTS lesion CASCADE;
DROP TABLE IF EXISTS cronica CASCADE;
DROP TABLE IF EXISTS noticia CASCADE;
DROP TABLE IF EXISTS acta_evento CASCADE;
DROP TABLE IF EXISTS acta_partido CASCADE;
DROP TABLE IF EXISTS estadisticas_partido CASCADE;
DROP TABLE IF EXISTS partido CASCADE;
DROP TABLE IF EXISTS jugador CASCADE;
DROP TABLE IF EXISTS equipo_calasanz CASCADE;
DROP TABLE IF EXISTS equipo CASCADE;
DROP TABLE IF EXISTS categoria CASCADE;
DROP TABLE IF EXISTS temporada CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;

-- 1. Tabla Usuarios
CREATE TABLE usuarios (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(30) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'ESTANDAR',
    activo BOOLEAN NOT NULL DEFAULT true,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ESTANDAR', 'JUGADOR', 'ENTRENADOR', 'COORDINADOR', 'DESARROLLADOR'))
);

CREATE UNIQUE INDEX uq_usuarios_username_lower ON usuarios (LOWER(username));
CREATE UNIQUE INDEX uq_usuarios_email_lower ON usuarios (LOWER(email));

-- 2. Tabla Temporada
CREATE TABLE temporada (
    id_temporada INT GENERATED BY DEFAULT AS IDENTITY,
    año VARCHAR(20) NOT NULL,
    CONSTRAINT pk_temporada PRIMARY KEY (id_temporada),
    CONSTRAINT uq_temporada_anio UNIQUE (año)
);

-- 3. Tabla Categoria (con duracion en minutos totales según §3 y §6.6)
CREATE TABLE categoria (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(50) NOT NULL,
    duracion INT NOT NULL DEFAULT 90,
    CONSTRAINT pk_categoria PRIMARY KEY (id_categoria),
    CONSTRAINT uq_nombre_categoria UNIQUE (nombre),
    CONSTRAINT ck_categoria_duracion CHECK (duracion IN (40, 50, 60, 70, 80, 90))
);

-- 4. Tabla Equipo (unificada propios y rivales — D1 y §6.6)
CREATE TABLE equipo (
    id_equipo INT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    categoria INT NOT NULL,
    competicion VARCHAR(100) NOT NULL,
    es_propio BOOLEAN NOT NULL DEFAULT false,
    id_entrenador INT NULL,
    CONSTRAINT pk_equipo PRIMARY KEY (id_equipo),
    CONSTRAINT uq_equipo_nombre_cat UNIQUE (nombre, categoria),
    CONSTRAINT fk_equipo_categoria FOREIGN KEY (categoria) REFERENCES categoria(id_categoria),
    CONSTRAINT fk_equipo_entrenador FOREIGN KEY (id_entrenador) REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    CONSTRAINT ck_equipo_competicion CHECK (CHAR_LENGTH(TRIM(competicion)) >= 1),
    CONSTRAINT ck_equipo_entrenador_propio CHECK (es_propio = true OR id_entrenador IS NULL)
);

CREATE UNIQUE INDEX uq_equipo_entrenador ON equipo (id_entrenador) WHERE id_entrenador IS NOT NULL;

-- 5. Tabla Jugador
CREATE TABLE jugador (
    id_jugador INT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(50) NOT NULL,
    ap1 VARCHAR(100) NOT NULL,
    ap2 VARCHAR(100) NULL,
    estatura DECIMAL(3,2) NULL,
    peso DECIMAL(5,2) NULL,
    equipo INT NOT NULL,
    dorsal INT NULL,
    posicion VARCHAR(30) NOT NULL,
    id_usuario INT NULL,
    activo BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT pk_jugador PRIMARY KEY (id_jugador),
    CONSTRAINT fk_jugador_equipo FOREIGN KEY (equipo) REFERENCES equipo(id_equipo),
    CONSTRAINT fk_jugador_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    CONSTRAINT ck_jugador_posicion CHECK (posicion IN ('Portero', 'Defensa', 'Centrocampista', 'Delantero')),
    CONSTRAINT ck_jugador_dorsal CHECK (dorsal IS NULL OR (dorsal >= 1 AND dorsal <= 99)),
    CONSTRAINT ck_jugador_estatura CHECK (estatura IS NULL OR (estatura >= 1.00 AND estatura <= 2.30)),
    CONSTRAINT ck_jugador_peso CHECK (peso IS NULL OR (peso >= 20.00 AND peso <= 200.00))
);

CREATE UNIQUE INDEX uq_jugador_usuario ON jugador (id_usuario) WHERE id_usuario IS NOT NULL;
CREATE UNIQUE INDEX uq_jugador_dorsal_activo ON jugador (equipo, dorsal) WHERE activo = true AND dorsal IS NOT NULL;

-- 6. Tabla Partido (permite partidos propios y entre rivales — D7 y §6.6)
CREATE TABLE partido (
    id_partido INT GENERATED BY DEFAULT AS IDENTITY,
    temporada INT NOT NULL,
    jornada INT NOT NULL,
    fecha_ini DATE NOT NULL,
    lugar VARCHAR(150) NULL,
    local INT NOT NULL,
    visitante INT NOT NULL,
    resultado_local INT NULL,
    resultado_visitante INT NULL,
    ganador INT NULL,
    evento VARCHAR(255) NULL,
    CONSTRAINT pk_partido PRIMARY KEY (id_partido),
    CONSTRAINT fk_partido_temporada FOREIGN KEY (temporada) REFERENCES temporada(id_temporada),
    CONSTRAINT fk_partido_local FOREIGN KEY (local) REFERENCES equipo(id_equipo),
    CONSTRAINT fk_partido_visitante FOREIGN KEY (visitante) REFERENCES equipo(id_equipo),
    CONSTRAINT fk_partido_ganador FOREIGN KEY (ganador) REFERENCES equipo(id_equipo),
    CONSTRAINT ck_jornada_positiva CHECK (jornada >= 1),
    CONSTRAINT ck_partido_equipos_distintos CHECK (local <> visitante),
    CONSTRAINT ck_partido_resultados_rango CHECK (
        (resultado_local IS NULL AND resultado_visitante IS NULL)
        OR (resultado_local BETWEEN 0 AND 99 AND resultado_visitante BETWEEN 0 AND 99)
    )
);

-- 7. Tabla Acta_Partido (árbitros y delegados del acta — §6.6)
CREATE TABLE acta_partido (
    partido INT NOT NULL,
    arbitro_principal VARCHAR(100) NULL,
    arbitro_asistente_1 VARCHAR(100) NULL,
    arbitro_asistente_2 VARCHAR(100) NULL,
    delegado_campo VARCHAR(100) NULL,
    delegado_equipo VARCHAR(100) NULL,
    CONSTRAINT pk_acta_partido PRIMARY KEY (partido),
    CONSTRAINT fk_acta_partido FOREIGN KEY (partido) REFERENCES partido(id_partido) ON DELETE CASCADE
);

-- 8. Tabla Acta_Evento (eventos minuto a minuto del acta — §6.6)
CREATE TABLE acta_evento (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    partido INT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    minuto INT NOT NULL,
    id_jugador INT NULL,
    id_jugador_2 INT NULL,
    color VARCHAR(10) NULL,
    autor_rival VARCHAR(100) NULL,
    CONSTRAINT pk_acta_evento PRIMARY KEY (id),
    CONSTRAINT fk_acta_evento_partido FOREIGN KEY (partido) REFERENCES partido(id_partido) ON DELETE CASCADE,
    CONSTRAINT fk_acta_evento_jugador FOREIGN KEY (id_jugador) REFERENCES jugador(id_jugador),
    CONSTRAINT fk_acta_evento_jugador_2 FOREIGN KEY (id_jugador_2) REFERENCES jugador(id_jugador),
    CONSTRAINT ck_acta_evento_tipo CHECK (tipo IN ('gol', 'gol_rival', 'tarjeta', 'sustitucion')),
    CONSTRAINT ck_acta_evento_minuto CHECK (minuto BETWEEN 0 AND 120),
    CONSTRAINT ck_acta_evento_color CHECK (
        (tipo = 'tarjeta' AND color IN ('amarilla', 'roja'))
        OR (tipo <> 'tarjeta' AND color IS NULL)
    )
);

-- 9. Tabla Estadisticas_Partido (totales calculados por partido y jugador)
CREATE TABLE estadisticas_partido (
    partido INT NOT NULL,
    id_jugador INT NOT NULL,
    id_equipo INT NOT NULL,
    estado VARCHAR(10) NOT NULL,
    mins_jugados INT NOT NULL DEFAULT 0,
    goles INT NOT NULL DEFAULT 0,
    goles_recibidos INT NOT NULL DEFAULT 0,
    asistencias INT NOT NULL DEFAULT 0,
    amarillas INT NOT NULL DEFAULT 0,
    roja BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT pk_estadisticas_partido PRIMARY KEY (partido, id_jugador),
    CONSTRAINT fk_estadisticas_partido FOREIGN KEY (partido) REFERENCES partido(id_partido) ON DELETE CASCADE,
    CONSTRAINT fk_estadisticas_jugador FOREIGN KEY (id_jugador) REFERENCES jugador(id_jugador),
    CONSTRAINT fk_estadisticas_equipo FOREIGN KEY (id_equipo) REFERENCES equipo(id_equipo),
    CONSTRAINT ck_estado CHECK (estado IN ('titular', 'suplente')),
    CONSTRAINT ck_minutos CHECK (mins_jugados BETWEEN 0 AND 120),
    CONSTRAINT ck_goles CHECK (goles >= 0),
    CONSTRAINT ck_goles_recibidos CHECK (goles_recibidos >= 0),
    CONSTRAINT ck_asistencias CHECK (asistencias >= 0),
    CONSTRAINT ck_amarillas CHECK (amarillas BETWEEN 0 AND 2)
);

-- 10. Tabla Cronica (máximo una por partido propio finalizado — §5 y §6.6)
CREATE TABLE cronica (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    partido INT NOT NULL,
    titulo VARCHAR(120) NOT NULL,
    texto TEXT NOT NULL,
    id_autor INT NOT NULL,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizada_en TIMESTAMPTZ NULL,
    CONSTRAINT pk_cronica PRIMARY KEY (id),
    CONSTRAINT uq_cronica_partido UNIQUE (partido),
    CONSTRAINT fk_cronica_partido FOREIGN KEY (partido) REFERENCES partido(id_partido) ON DELETE CASCADE,
    CONSTRAINT fk_cronica_autor FOREIGN KEY (id_autor) REFERENCES usuarios(id_usuario),
    CONSTRAINT ck_cronica_titulo CHECK (CHAR_LENGTH(TRIM(titulo)) BETWEEN 3 AND 120),
    CONSTRAINT ck_cronica_texto CHECK (CHAR_LENGTH(TRIM(texto)) BETWEEN 50 AND 3000)
);

-- 11. Tabla Noticia / Evento
CREATE TABLE noticia (
    id_noticia INT GENERATED BY DEFAULT AS IDENTITY,
    titulo VARCHAR(150) NOT NULL,
    cuerpo TEXT NOT NULL,
    tipo VARCHAR(15) NOT NULL DEFAULT 'noticia',
    fecha_evento DATE NULL,
    publicada_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_autor INT NOT NULL,
    CONSTRAINT pk_noticia PRIMARY KEY (id_noticia),
    CONSTRAINT fk_noticia_autor FOREIGN KEY (id_autor) REFERENCES usuarios(id_usuario),
    CONSTRAINT ck_noticia_titulo CHECK (CHAR_LENGTH(TRIM(titulo)) BETWEEN 1 AND 150),
    CONSTRAINT ck_noticia_cuerpo CHECK (CHAR_LENGTH(TRIM(cuerpo)) BETWEEN 1 AND 10000),
    CONSTRAINT ck_noticia_tipo CHECK (tipo IN ('noticia', 'evento')),
    CONSTRAINT ck_noticia_fecha_evento CHECK (tipo = 'noticia' OR fecha_evento IS NOT NULL)
);

-- 12. Tabla Lesion
CREATE TABLE lesion (
    id_lesion INT GENERATED BY DEFAULT AS IDENTITY,
    id_jugador INT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_estimada_vuelta DATE NOT NULL,
    fecha_alta DATE NULL,
    activa BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT pk_lesion PRIMARY KEY (id_lesion),
    CONSTRAINT fk_lesion_jugador FOREIGN KEY (id_jugador) REFERENCES jugador(id_jugador) ON DELETE CASCADE,
    CONSTRAINT ck_lesion_fechas CHECK (fecha_estimada_vuelta >= fecha_inicio),
    CONSTRAINT ck_lesion_fecha_alta CHECK (fecha_alta IS NULL OR fecha_alta >= fecha_inicio)
);

CREATE UNIQUE INDEX uq_lesion_activa_jugador ON lesion (id_jugador) WHERE activa = true;

-- 13. Tabla Apunte_Entrenador
CREATE TABLE apunte_entrenador (
    id_apunte INT GENERATED BY DEFAULT AS IDENTITY,
    id_equipo INT NOT NULL,
    id_rival INT NULL,
    id_partido INT NULL,
    texto TEXT NOT NULL,
    id_autor INT NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_apunte_entrenador PRIMARY KEY (id_apunte),
    CONSTRAINT fk_apunte_equipo FOREIGN KEY (id_equipo) REFERENCES equipo(id_equipo) ON DELETE CASCADE,
    CONSTRAINT fk_apunte_rival FOREIGN KEY (id_rival) REFERENCES equipo(id_equipo) ON DELETE SET NULL,
    CONSTRAINT fk_apunte_partido FOREIGN KEY (id_partido) REFERENCES partido(id_partido) ON DELETE SET NULL,
    CONSTRAINT fk_apunte_autor FOREIGN KEY (id_autor) REFERENCES usuarios(id_usuario),
    CONSTRAINT ck_apunte_texto CHECK (CHAR_LENGTH(TRIM(texto)) BETWEEN 1 AND 2000)
);

-- 14. Tabla Solicitud_Acceso
CREATE TABLE solicitud_acceso (
    id_solicitud INT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario INT NOT NULL,
    rol_solicitado VARCHAR(20) NOT NULL,
    id_jugador INT NULL,
    id_equipo INT NULL,
    mensaje TEXT NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'pendiente',
    comentario_resolucion TEXT NULL,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resuelta_en TIMESTAMPTZ NULL,
    CONSTRAINT pk_solicitud_acceso PRIMARY KEY (id_solicitud),
    CONSTRAINT fk_solicitud_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_solicitud_jugador FOREIGN KEY (id_jugador) REFERENCES jugador(id_jugador) ON DELETE SET NULL,
    CONSTRAINT fk_solicitud_equipo FOREIGN KEY (id_equipo) REFERENCES equipo(id_equipo) ON DELETE SET NULL,
    CONSTRAINT ck_solicitud_rol CHECK (rol_solicitado IN ('JUGADOR', 'ENTRENADOR')),
    CONSTRAINT ck_solicitud_estado CHECK (estado IN ('pendiente', 'aprobada', 'rechazada')),
    CONSTRAINT ck_solicitud_mensaje CHECK (CHAR_LENGTH(TRIM(mensaje)) BETWEEN 5 AND 500),
    CONSTRAINT ck_solicitud_objetivo CHECK (
        (rol_solicitado = 'JUGADOR' AND id_jugador IS NOT NULL AND id_equipo IS NULL)
        OR (rol_solicitado = 'ENTRENADOR' AND id_equipo IS NOT NULL AND id_jugador IS NULL)
    )
);

CREATE UNIQUE INDEX uq_solicitud_pendiente_usuario ON solicitud_acceso (id_usuario) WHERE estado = 'pendiente';

