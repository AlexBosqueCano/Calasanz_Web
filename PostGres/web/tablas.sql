    estado varchar(10) NOT NULL DEFAULT 'pendiente',
    comentario_resolucion varchar(500),
    id_resolutor int,
    creada_en timestamptz NOT NULL DEFAULT now(),
    resuelta_en timestamptz,
    CONSTRAINT pk_solicitud_acceso PRIMARY KEY(id_solicitud),
    CONSTRAINT fk_solicitud_usuario FOREIGN KEY(id_usuario)
        REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_solicitud_jugador FOREIGN KEY(id_jugador)
        REFERENCES jugador(id_jugador),
    CONSTRAINT fk_solicitud_equipo FOREIGN KEY(id_equipo)
        REFERENCES equipo(id_equipo),
    CONSTRAINT fk_solicitud_resolutor FOREIGN KEY(id_resolutor)
        REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    CONSTRAINT ck_solicitud_rol CHECK (rol_solicitado IN ('JUGADOR', 'ENTRENADOR')),
    CONSTRAINT ck_solicitud_estado CHECK (estado IN ('pendiente', 'aprobada', 'rechazada')),
    CONSTRAINT ck_solicitud_mensaje CHECK (char_length(mensaje) BETWEEN 5 AND 500),
    -- JUGADOR pide una ficha; ENTRENADOR pide un equipo; nunca las dos cosas.
    CONSTRAINT ck_solicitud_vinculo CHECK (
        (rol_solicitado = 'JUGADOR' AND id_jugador IS NOT NULL AND id_equipo IS NULL)
        OR (rol_solicitado = 'ENTRENADOR' AND id_equipo IS NOT NULL AND id_jugador IS NULL)),
    -- Pendiente <=> sin fecha de resolución.
    CONSTRAINT ck_solicitud_resuelta CHECK ((estado = 'pendiente') = (resuelta_en IS NULL)),
    -- Rechazar exige comentario.
    CONSTRAINT ck_solicitud_rechazo CHECK (estado <> 'rechazada' OR comentario_resolucion IS NOT NULL)
);

-- Una sola solicitud pendiente por usuario.
CREATE UNIQUE INDEX uq_solicitud_pendiente ON solicitud_acceso (id_usuario)
    WHERE estado = 'pendiente';


